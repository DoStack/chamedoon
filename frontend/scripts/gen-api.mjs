// Generates TS types from the backend contract. The output is gitignored, so
// `npm run typecheck` always checks the frontend against the current contract.
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const spec = resolve(root, '../backend/home_api/openapi.yaml')
const out = resolve(root, 'src/api/schema.gen.ts')
const codesOut = resolve(root, 'src/api/codes.gen.ts')

if (!existsSync(spec)) {
  console.log('gen:api skipped: backend/home_api/openapi.yaml does not exist yet')
  process.exit(0)
}

mkdirSync(dirname(out), { recursive: true })
// Relative paths: the checkout path can hold spaces, and this goes through a shell.
const args = ['openapi-typescript', relative(root, spec), '-o', relative(root, out)]
const result = spawnSync('npx', args, { stdio: 'inherit', cwd: root, shell: true })
if (result.status) process.exit(result.status)

// `x-error-codes` is not in the OpenAPI type output, so screens get the union from here.
const codes = new Set()
let inList = false
for (const line of readFileSync(spec, 'utf8').split(/\r?\n/)) {
  if (/^\s*x-error-codes:\s*$/.test(line)) inList = true
  else if (inList) {
    const item = line.match(/^\s*-\s*([a-z][a-z0-9_]*)\s*$/)
    if (item) codes.add(item[1])
    else inList = false
  }
}
const union = [...codes].sort().map((code) => `  | '${code}'`).join('\n')
writeFileSync(codesOut, `// Generated by scripts/gen-api.mjs. Every x-error-codes value in the contract.\nexport type ServerCode =\n${union}\n`)
